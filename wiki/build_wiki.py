def main():
    check = '--check' in sys.argv
    stale = []
    for name, fn in PAGES.items():
        want = fn()
        path = HERE / name
        if check:
            if not path.exists() or path.read_text() != want:
                stale.append(name)
        else:
            path.write_text(want)
    if check:
        if stale:
            print('STALE wiki pages: ' + ', '.join(stale))
            print('       run: python3 wiki/build_wiki.py')
            sys.exit(1)
        print(f'wiki is current ({len(PAGES)} pages)')
    else:
        print(f'wiki: {len(PAGES)} pages written')


if __name__ == '__main__':
    main()
