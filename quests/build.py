"""Builds quests/registry/quests.json: the quests, side quests, games,
treasures and easter eggs of the bundle, as play.

Most entries are generated by rule from registries the bundle already holds,
so an entry can only point at something that exists:

  side quests   one per hall that has lessons (lessons/registry/lessons.json),
                gated by that hall's own lessons; one per simulator seat
                (sims/registry/sims.json) and one per tool crib, gated by every
                lesson that puts a learner in that seat or at that crib
  games         one per arcade game, gated by the lessons that use the seat the
                game's content is read from (ladder order, at most two)
  page eggs     three per page this pack hooks: a knock on the page's heading,
                a typed word, and a hidden cache (explore-only, band K-5)

The main chain, the module treasures and the quest-page eggs are AUTHORED
below. `unlock_text` is generated from `requires`, never typed. Every id in
`requires` must resolve or the build stops with a named error; there are no
defaults on registry data.

Quests and badges are play: they never enter a completion record and certify
nothing. The registry says so in `honesty`.
"""
