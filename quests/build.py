def need(d, k, where):
    if not isinstance(d, dict):
        raise TypeError(f'{where}: expected an object to read {k!r} from, got {type(d).__name__}')
    if k not in d:
        raise KeyError(f'{where}: required field {k!r} is missing')
    return d[k]


def load(rel):
    return json.loads((ROOT / rel).read_text(encoding='utf-8'))


LESSONS_PATH = 'lessons/registry/lessons.json'
HALLS_PATH = 'pack/registry/halls.json'
SIMS_PATH = 'sims/registry/sims.json'

lessons_reg = load(LESSONS_PATH)
LESSONS = need(lessons_reg, 'lessons', LESSONS_PATH)
LADDER = need(lessons_reg, 'ladder', LESSONS_PATH)
LAYERS = need(LADDER, 'layers', f'{LESSONS_PATH}#ladder')
HALLS = {need(h, 'slug', HALLS_PATH): need(h, 'name', HALLS_PATH) for h in need(load(HALLS_PATH), 'halls', HALLS_PATH)}
SIMS = need(load(SIMS_PATH), 'sims', SIMS_PATH)

LAYER_OF = {lid: int(depth) for depth, ids in LAYERS.items() for lid in ids}
KEY_ORDER = list(LESSONS)


def course_order(ids):
    """The ladder layer, then the registry's key order: how the lessons page orders a course."""
    for i in ids:
        if i not in LAYER_OF:
            raise KeyError(f'{LESSONS_PATH}#ladder.layers holds no layer for lesson {i!r}')
    return sorted(set(ids), key=lambda i: (LAYER_OF[i], KEY_ORDER.index(i)))


def lessons_where(pred):
    return course_order([lid for lid, L in LESSONS.items() if any(pred(s) for s in need(L, 'steps', lid))])


def req(lessons=(), halls=(), quests=()):
    return {'lessons': list(lessons), 'halls': list(halls), 'quests': list(quests)}


Q = []


def add(id, kind, title, world, requires, hint, badge_label, place=None, band=None, trigger=None, target=None,
        riddle=None):
    e = {'id': id, 'kind': kind, 'title': title, 'world': world, 'requires': requires, 'hint': hint,
         'reward': {'badge': 'badge-' + id, 'label': badge_label}, 'provenance': 'AUTHORED'}
    if place is not None:
        e['place'] = place
    if band is not None:
        e['band'] = band
    if trigger is not None:
        e['trigger'] = trigger
    if target is not None:
        e['target'] = target
    if riddle is not None:
        e['riddle'] = riddle
    Q.append(e)


