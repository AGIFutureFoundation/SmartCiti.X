            sid = need(site, 'id', f'{WILDS_PATH}#{wid}.sites')
            named = [need(l, 'id', f'{WILDS_PATH}#{sid}.lessons') for l in need(site, 'lessons', f'{WILDS_PATH}#{sid}')]
