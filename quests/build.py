by_id = {q['id']: q for q in Q}
KINDS = ('main', 'side', 'game', 'treasure', 'egg')
BANDS = ('K-5', '6-8', '9-10', '11-12')
for q in Q:
    if q['kind'] not in KINDS:
        raise ValueError(f'{q["id"]}: kind {q["kind"]!r} is not one of {KINDS}')
    if 'band' in q and q['band'] not in BANDS:
        raise ValueError(f'{q["id"]}: band {q["band"]!r} is not one of {BANDS}')
    w = q['world']
    if not (w == 'campus' or w.startswith('hall:') or w.startswith('wilds:') or w.startswith('page:')
            or w == 'parishes' or w.startswith('parish:')):
        raise ValueError(f'{q["id"]}: world {w!r} is not campus | hall:<id> | wilds:<id> | page:<path> | parishes | parish:<fips>')
    if w.startswith('parish:') and w[7:] not in _fips_all:
        raise KeyError(f'{q["id"]}: world names parish {w[7:]!r}, which {LAYERS_PATH} does not hold')
    if w.startswith('hall:') and w[5:] not in HALLS:
        raise KeyError(f'{q["id"]}: world names hall {w[5:]!r}, which {HALLS_PATH} does not hold')
    r = q['requires']
    for lid in r['lessons']:
        if lid not in LESSONS:
            raise KeyError(f'{q["id"]}: requires lesson {lid!r}, which {LESSONS_PATH} does not hold')
    for h in r['halls']:
        if h not in HALLS:
            raise KeyError(f'{q["id"]}: requires hall {h!r}, which {HALLS_PATH} does not hold')
        if h not in by_hall:
            raise KeyError(f'{q["id"]}: requires hall {h!r}, which has no lesson that could satisfy it')
    for qid in r['quests']:
        if qid not in by_id:
            raise KeyError(f'{q["id"]}: requires quest {qid!r}, which is not in this registry')
    if 'band' in q and q['band'] == 'K-5':
        if r['lessons'] or r['halls']:
            raise AssertionError(f'{q["id"]}: a K-5 entry must be explore-only (no lessons, no seats)')


def unlock_text(r):
    parts = []
    if r['lessons']:
        parts.append('walk ' + ', '.join(f'"{LESSONS[i]["title"]}"' for i in r['lessons']))
    if r['halls']:
        parts.append('finish a lesson in ' + ', '.join(HALLS[h] for h in r['halls']))
    if r['quests']:
        parts.append('finish ' + ', '.join(f'"{by_id[i]["title"]}"' for i in r['quests']))
    return ('Open to everyone.' if not parts else 'To unlock: ' + '; '.join(parts) + '.')


for q in Q:
    q['unlock_text'] = unlock_text(q['requires'])

# cycle check over requires.quests
state = {}


def visit(i, path):
    if state.get(i) == 1:
        raise AssertionError('quest requirements form a cycle: ' + ' -> '.join(path + [i]))
    if state.get(i) == 2:
        return
    state[i] = 1
    for j in by_id[i]['requires']['quests']:
        visit(j, path + [i])
    state[i] = 2


for i in by_id:
    visit(i, [])

